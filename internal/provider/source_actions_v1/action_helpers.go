// Package source_actions_v1 implements hand-written Terraform Plugin
// Framework "actions" (https://developer.hashicorp.com/terraform/language/invoke-actions)
// wrapping SailPoint's imperative source aggregation/sync operations:
// aggregate accounts, aggregate entitlements, and sync source attributes.
//
// These operations have no natural 1:1 REST CRUD resource to model - they
// are one-shot background jobs, not persistent objects - so, like
// source_load_entitlement_wait_v1 (the pre-Actions workaround this package
// supersedes for entitlement aggregation), they are hand-written rather than
// generated by the OpenAPI codegen pipeline. Unlike that resource, actions
// don't need triggers-map/RequiresReplace tricks to force re-invocation:
// Terraform's native action_trigger lifecycle blocks (before_create,
// after_create, before_update, after_update - before_destroy/after_destroy
// are not supported as of Terraform 1.14) invoke them directly, or a
// practitioner can invoke them manually via `terraform apply -invoke=...`.
package source_actions_v1

import (
	"context"
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/hashicorp/terraform-plugin-framework/action"
	"github.com/hashicorp/terraform-plugin-log/tflog"

	sailpoint "github.com/sailpoint-oss/golang-sdk/v3"
	"github.com/sailpoint-oss/golang-sdk/v3/task_management"

	"terraform-provider-identitynow/internal/provider/util"
)

const (
	defaultInvokeTimeout = 30 * time.Minute
	initialPollInterval  = 2 * time.Second
	maxPollInterval      = 15 * time.Second
	// progressReportInterval throttles SendProgress calls so long polls don't
	// flood Terraform/HCP Terraform with an event on every poll tick.
	progressReportInterval = 30 * time.Second
)

// clientProvider is satisfied by internal/provider.identitynowProvider
// without this package needing to import it (which would create an import
// cycle since provider.go imports this package to register actions).
type clientProvider interface {
	GetClient() *sailpoint.APIClient
}

// configureClient implements the shared ActionWithConfigure logic used by
// all three actions in this package, mirroring the resource-side
// clientProvider pattern already established throughout this provider.
func configureClient(req action.ConfigureRequest, resp *action.ConfigureResponse) *sailpoint.APIClient {
	if req.ProviderData == nil {
		return nil
	}

	cp, ok := req.ProviderData.(clientProvider)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Action Configure Type",
			fmt.Sprintf("Expected a provider client, got: %T. Please report this issue to the provider developers.", req.ProviderData),
		)
		return nil
	}

	return cp.GetClient()
}

// parseTimeout returns d parsed as a Go duration, or defaultInvokeTimeout
// when d is empty. Action schema attributes cannot be Computed (unlike
// resource schemas), so unlike source_load_entitlement_wait_v1's
// create_timeout, this default can't be expressed via schema defaults and
// must be applied here instead.
func parseTimeout(d string) (time.Duration, error) {
	if strings.TrimSpace(d) == "" {
		return defaultInvokeTimeout, nil
	}

	parsed, err := time.ParseDuration(d)
	if err != nil {
		return 0, fmt.Errorf("timeout must be a valid Go duration such as %q: %w", "30m", err)
	}
	if parsed <= 0 {
		return 0, fmt.Errorf("timeout must be greater than zero")
	}
	return parsed, nil
}

// waitForTaskCompletion polls task_management's GetTaskStatusV1 until the
// task reaches a terminal completion status, reporting throttled progress
// via sendProgress. Shared by the aggregate-accounts and
// aggregate-entitlements actions; ported from
// source_load_entitlement_wait_v1's waitForTaskCompletion.
func waitForTaskCompletion(ctx context.Context, client *sailpoint.APIClient, taskID string, sendProgress func(action.InvokeProgressEvent)) error {
	lastReport := time.Now()
	for attempt := 0; ; attempt++ {
		status, httpResp, err := client.TaskManagementAPI.GetTaskStatusV1(ctx, taskID).Execute()
		if err != nil {
			if ctx.Err() != nil {
				return fmt.Errorf("timed out while polling task status: %w", ctx.Err())
			}
			return fmt.Errorf("retrieving task status: %s", util.SailpointErrorDetail(err, httpResp))
		}
		if status == nil {
			return fmt.Errorf("task status response for task %q was empty", taskID)
		}

		// Live testing of the pre-existing source_load_entitlement_wait_v1
		// resource showed `completed` and `completionStatus` are not always
		// written atomically: a poll can observe `completed` already set
		// while `completionStatus` is still empty/null for a brief window.
		// Treat that combination as "not yet finished" and keep polling.
		if finished, completionStatus := taskCompletionResult(status); finished {
			if !isSuccessfulCompletionStatus(completionStatus) {
				return fmt.Errorf("task %q completed with status %q", taskID, completionStatus)
			}
			tflog.Info(ctx, "Task completed", map[string]interface{}{"task_id": taskID, "completion_status": completionStatus})
			return nil
		}

		interval := pollInterval(attempt)
		if sendProgress != nil && time.Since(lastReport) >= progressReportInterval {
			sendProgress(action.InvokeProgressEvent{Message: fmt.Sprintf("Waiting for task %s to finish...", taskID)})
			lastReport = time.Now()
		}
		tflog.Debug(ctx, "Waiting for task completion", map[string]interface{}{"task_id": taskID, "poll_interval": interval.String()})
		if err := sleepWithContext(ctx, interval); err != nil {
			return fmt.Errorf("timed out while waiting for task %q to complete: %w", taskID, err)
		}
	}
}

func normalizedCompletionStatus(status task_management.NullableString) string {
	if !status.IsSet() || status.Get() == nil {
		return ""
	}
	return strings.ToUpper(strings.TrimSpace(*status.Get()))
}

func isSuccessfulCompletionStatus(status string) bool {
	return status == "SUCCESS" || status == "WARNING"
}

// taskCompletionResult decides whether a polled task status should be
// treated as finished. See waitForTaskCompletion's comment on why `completed`
// alone is not sufficient.
func taskCompletionResult(status *task_management.TaskStatus) (finished bool, completionStatus string) {
	if status == nil {
		return false, ""
	}
	completionStatus = normalizedCompletionStatus(status.CompletionStatus)
	if status.Completed.IsSet() && status.Completed.Get() != nil && completionStatus != "" {
		return true, completionStatus
	}
	return false, ""
}

func pollInterval(attempt int) time.Duration {
	if attempt <= 0 {
		return initialPollInterval
	}

	interval := initialPollInterval
	for i := 0; i < attempt && interval < maxPollInterval; i++ {
		interval *= 2
		if interval >= maxPollInterval {
			return maxPollInterval
		}
	}
	return interval
}

func sleepWithContext(ctx context.Context, d time.Duration) error {
	timer := time.NewTimer(d)
	defer timer.Stop()

	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-timer.C:
		return nil
	}
}

// emptyMultipartFile creates a throwaway empty temp file so the generated
// request builders for ImportAccountsV1/ImportEntitlementsV1 take their
// correct multipart-encoding code path even when there is no real file to
// upload (non-delimited-file sources ignore the request body entirely). See
// source_load_entitlement_wait_v1's Create comment for the underlying
// golang-sdk/v3 multipart Content-Type bug this works around.
func emptyMultipartFile(namePrefix string) (*os.File, error) {
	f, err := os.CreateTemp("", namePrefix+"-*.tmp")
	if err != nil {
		return nil, fmt.Errorf("creating empty temp file: %w", err)
	}
	return f, nil
}
